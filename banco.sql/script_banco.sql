-- ============================================
-- RESUMO POR CURSO E STATUS
-- ============================================
SELECT
    C.NOME AS CURSO,
    QS.STATUS,
    COUNT(*) AS TOTAL
FROM QUESTAO_STAGING QS
JOIN PROVA P ON P.ID = QS.PROVA_ID
JOIN CURSO C ON C.ID = P.CURSO_ID
GROUP BY C.NOME, QS.STATUS
ORDER BY C.NOME, QS.STATUS;


-- ============================================
-- TOTAL DE QUESTÕES POR CURSO
-- ============================================
SELECT
    C.NOME AS CURSO,
    COUNT(*) AS TOTAL
FROM QUESTAO_STAGING QS
JOIN PROVA P ON P.ID = QS.PROVA_ID
JOIN CURSO C ON C.ID = P.CURSO_ID
GROUP BY C.NOME
ORDER BY C.NOME;

-- ============================================
-- O QUE NÃO ESTÁ COMO COMPLETA
-- ============================================
SELECT
    C.NOME AS CURSO,
    QS.NUMERO,
    QS.STATUS,
    QS.CONFIANCA,
    QS.PARSE_STRATEGY,
    QS.OBSERVACAO
FROM QUESTAO_STAGING QS
JOIN PROVA P ON P.ID = QS.PROVA_ID
JOIN CURSO C ON C.ID = P.CURSO_ID
WHERE QS.STATUS <> 'COMPLETA'
ORDER BY C.NOME, QS.NUMERO;



DROP TABLE GABARITO, ALTERNATIVA, QUESTAO, PROVA, CURSO, ANO CASCADE;